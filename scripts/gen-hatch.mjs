// Generates the hand-drawn hatch tile once, from the prototype's fixed seed,
// and writes it as static CSS custom properties. Run: node scripts/gen-hatch.mjs
// The output is committed; the app never re-randomises the tile at runtime.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'src', 'design')

// Split complementary palette inks (see tokens.css).
const INK = { text: '#F2F4FF', bg: '#0B0D1C', text3: '#5D6380' }

function hatchGeom() {
  let seed = 20261021
  const r = () => {
    seed |= 0; seed = seed + 0x6D2B79F5 | 0
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed)
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t
    return ((t ^ t >>> 14) >>> 0) / 4294967296
  }
  const n = 5, R2 = Math.SQRT2
  let sp = Array.from({ length: n }, () => 5 + r() * 3)
  const k = (48 / R2) / sp.reduce((a, b) => a + b)
  sp = sp.map(v => v * k)
  let c = r() * 12
  const L = 48 * R2, lines = []
  for (let i = 0; i < n; i++) {
    c += sp[i] * R2
    const a = (45 + (r() * 6 - 3)) * Math.PI / 180, dx = Math.cos(a), dy = -Math.sin(a), nx = Math.sin(a), ny = Math.cos(a)
    const cx = c / 2, cy = c / 2
    const t0 = r() < 0.4 ? 0.06 + r() * 0.22 : r() * 0.03, t1 = r() < 0.4 ? 0.06 + r() * 0.22 : r() * 0.03
    const ph1 = r() * 6.28, ph2 = r() * 6.28, amp1 = 0.35 + r() * 0.35, amp2 = 0.15 + r() * 0.2
    const pts = []
    for (let j = 0; j <= 24; j++) {
      const t = t0 + (1 - t0 - t1) * j / 24, s = (t - 0.5) * L
      const w = amp1 * Math.sin(Math.PI * 2 * t + ph1) + amp2 * Math.sin(Math.PI * 5 * t + ph2)
      pts.push([cx + dx * s + nx * w, cy + dy * s + ny * w])
    }
    const chunks = [[0, 9], [8, 17], [16, 24]].map(([s0, s1]) => ({ w: 1 + r() * 1.2, d: 'M' + pts.slice(s0, s1 + 1).map(p => p[0].toFixed(2) + ' ' + p[1].toFixed(2)).join('L') }))
    lines.push({ op: 0.7 + r() * 0.3, chunks })
  }
  return lines
}

const geom = hatchGeom()

function hatchSvg(color, alpha) {
  const body = geom.map(l => `<g opacity='${(l.op * alpha).toFixed(3)}'>${l.chunks.map(c => `<path d='${c.d}' stroke-width='${c.w.toFixed(2)}'/>`).join('')}</g>`).join('')
  let uses = ''
  ;[-48, 0, 48].forEach(x => [-48, 0, 48].forEach(y => { uses += `<use href='#h' xlink:href='#h' x='${x}' y='${y}'/>` }))
  return `<svg xmlns='http://www.w3.org/2000/svg' xmlns:xlink='http://www.w3.org/1999/xlink' width='48' height='48' viewBox='0 0 48 48'><defs><g id='h' fill='none' stroke='${color}' stroke-linecap='round' stroke-linejoin='round'>${body}</g></defs>${uses}</svg>`
}

const uri = (color, alpha) => `url("data:image/svg+xml,${encodeURIComponent(hatchSvg(color, alpha))}")`

const css = `/* GENERATED by scripts/gen-hatch.mjs. Do not edit by hand.
   Hand-drawn hatch: one fixed 48px seamless SVG tile, seed 20261021,
   5 strokes at 42-48deg, 1-2.2px, 5-8px gaps. Same geometry for every ink. */
:root {
  --kb-hatch-light: ${uri(INK.text, 0.2)};   /* text @ 20%: dark + raised cards */
  --kb-hatch-dark: ${uri(INK.bg, 0.16)};     /* bg @ 16%: lime cards */
  --kb-hatch-second: ${uri(INK.text, 0.2)};  /* text @ 20%: second (blue) cards */
  --kb-hatch-seg: ${uri(INK.text3, 0.75)};   /* text-3 @ 75%: empty bar segments */
}
`

writeFileSync(join(out, 'hatch.css'), css)
writeFileSync(join(out, 'hatch.svg'), hatchSvg(INK.text, 0.2).replaceAll("'", '"') + '\n')
console.log('wrote src/design/hatch.css and src/design/hatch.svg')
